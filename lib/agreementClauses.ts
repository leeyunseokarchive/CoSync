export function getClauseTemplate(field: keyof OnboardingAnswers, option: string): string {
  return CLAUSE_TEMPLATES[field]?.[option as ClauseOption] ?? "";
}

export type ResolvedItem = {
  option: string;
  text?: string; // 편집된 조항 (없으면 템플릿 사용)
  source: "match" | "consensus";
};

// QUESTION_CONFIGS 순서로 조항 배열 생성. resolved에 없는 필드는 제외.
export function buildClauses(resolved: Partial<Record<keyof OnboardingAnswers, ResolvedItem>>): Clause[] {
  const clauses: Clause[] = [];
  for (const q of QUESTION_CONFIGS) {
    const r = resolved[q.field];
    if (!r) continue;
    const text = r.text?.trim() || getClauseTemplate(q.field, r.option);
    if (!text) continue;
    clauses.push({ field: q.field, cat: q.cat, option: r.option, text, source: r.source });
  }
  return clauses;
}

export function groupByChapter(clauses: Clause[]): Chapter[] {
  return CAT_LABELS.map((label, cat) => ({
    cat,
    label,
    clauses: clauses.filter(c => c.cat === cat),
  })).filter(ch => ch.clauses.length > 0);
}
